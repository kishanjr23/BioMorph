"""Phase 3: verify the PN -> KC -> top-k encoder on real data.

Usage:  python scripts/encoder_diagnostics.py

Diagnostic only. No detection results are produced here. The P1 preprocessor
is fitted on all Batch-1 rows (all gases), because these figures describe the
encoder, not a held-out-gas experiment.

Writes
    reports/figures/encoder_similarity.png     input cosine vs code Jaccard
    reports/figures/encoder_kc_usage.png       KC firing-rate histogram
    reports/figures/encoder_raster.png         60 Batch-1 samples x 2000 KCs
    reports/figures/encoder_overlap_by_batch.png  same-gas vs other-gas overlap with Batch 1
    reports/phase3_encoder.md                  numbers
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from biomorph.data import GAS_NAMES, N_BATCHES, load_all  # noqa: E402
from biomorph.fly.encoder import FlyEncoder, on_off  # noqa: E402
from biomorph.preprocess import Preprocessor  # noqa: E402

FIG = ROOT / "reports" / "figures"
SEED = 0
N_SEEDS_STABILITY = 5
MAX_PER_CELL = 300


def jaccard_matrix(H1, H2, k):
    O = H1.astype(np.int32) @ H2.T.astype(np.int32)
    return O / (2 * k - O)


def cosine_matrix(A, B):
    A = A / np.linalg.norm(A, axis=1, keepdims=True)
    B = B / np.linalg.norm(B, axis=1, keepdims=True)
    return A @ B.T


def main():
    ds = load_all()
    b1 = ds.batch == 1
    pre = Preprocessor("P1").fit(ds.X[b1])
    Z = pre.transform(ds.X)
    P = on_off(Z)
    enc = FlyEncoder(seed=SEED)
    H = enc.encode(Z)
    k, m = enc.k, enc.m
    rng = np.random.default_rng(0)
    lines = [f"# Phase 3: encoder diagnostics", "",
             f"Generated by `scripts/encoder_diagnostics.py` on {date.today()}. "
             f"Encoder: m = {m} KCs, s = {enc.s} inputs per KC, k = {k} active "
             f"({k / m:.0%}), ON/OFF PN input (256 channels), seed {SEED}. "
             "P1 preprocessing fitted on all Batch-1 rows. Diagnostic only, no "
             "detection results.", ""]

    # ---- basic checks
    active = H.sum(axis=1)
    fan = enc.effective_fan_in()
    nz_pn = (P > 0).sum(axis=1)
    lines += ["## 1. Structural checks", "",
              f"- Active KCs per sample: min {active.min()}, max {active.max()} "
              f"(expected exactly {k}) over all {len(H)} samples",
              f"- Non-zero PN channels per sample: mean {nz_pn.mean():.1f} of 256 "
              f"(ON/OFF: at most 128 can be non-zero)",
              f"- Effective fan-in (distinct features per KC): mean {fan.mean():.2f}; "
              f"{(fan < enc.s).mean():.1%} of KCs are wired to both the ON and OFF "
              "channel of at least one feature", ""]

    # ---- 1. similarity preservation (Batch 1 pairs)
    idx = np.flatnonzero(b1)
    i, j = rng.choice(idx, 4000), rng.choice(idx, 4000)
    keep = i != j
    i, j = i[keep], j[keep]
    cos = np.sum(P[i] * P[j], 1) / (np.linalg.norm(P[i], axis=1) * np.linalg.norm(P[j], axis=1))
    ov = np.sum(H[i] & H[j], 1)
    jac = ov / (2 * k - ov)
    rho = spearmanr(cos, jac).statistic
    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    same = ds.gas[i] == ds.gas[j]
    ax.scatter(cos[~same], jac[~same], s=4, alpha=0.3, label="different gas")
    ax.scatter(cos[same], jac[same], s=4, alpha=0.3, label="same gas")
    bins = np.linspace(cos.min(), cos.max(), 15)
    mid = 0.5 * (bins[1:] + bins[:-1])
    which = np.digitize(cos, bins[1:-1])
    ax.plot(mid, [jac[which == b].mean() if (which == b).any() else np.nan
                  for b in range(len(mid))], "k-", lw=2, label="binned mean")
    ax.set_xlabel("cosine similarity of PN inputs")
    ax.set_ylabel("Jaccard overlap of KC codes")
    ax.set_title(f"Similarity preservation, Batch 1 (Spearman ρ = {rho:.3f})")
    ax.legend(markerscale=3, fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / "encoder_similarity.png", dpi=130)
    plt.close(fig)
    lines += ["## 2. Similarity preservation", "",
              f"{len(i)} random Batch-1 pairs: Spearman ρ(input cosine, code Jaccard) "
              f"= **{rho:.3f}**. Random-code chance Jaccard ≈ "
              f"{(k / m) / (2 - k / m):.3f}.", "",
              "![similarity](figures/encoder_similarity.png)", ""]

    # ---- 2. KC usage
    rate_b1 = H[b1].mean(axis=0)
    rate_all = H.mean(axis=0)
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.hist(rate_b1, bins=60)
    ax.axvline(k / m, color="k", ls=":", label=f"uniform use = {k / m:.2f}")
    ax.set_xlabel("fraction of Batch-1 samples in which the KC fires")
    ax.set_ylabel("number of KCs")
    ax.set_title(f"KC usage, Batch 1: {np.sum(rate_b1 == 0)} of {m} never fire")
    ax.legend()
    fig.tight_layout()
    fig.savefig(FIG / "encoder_kc_usage.png", dpi=130)
    plt.close(fig)
    dead_seeds = [int((FlyEncoder(seed=s).encode(Z[b1]).sum(0) == 0).sum())
                  for s in range(N_SEEDS_STABILITY)]
    lines += ["## 3. KC usage (lifetime sparsity)", "",
              f"- Batch 1: **{int(np.sum(rate_b1 == 0))}** of {m} KCs never fire "
              f"({np.mean(rate_b1 == 0):.1%}); all batches: "
              f"{int(np.sum(rate_all == 0))}.",
              f"- Dead KCs in Batch 1 for seeds 0-{N_SEEDS_STABILITY - 1}: {dead_seeds}",
              f"- KCs firing in more than 50% of Batch-1 samples: "
              f"{int(np.sum(rate_b1 > 0.5))}",
              f"- Max firing rate of one KC in Batch 1: {rate_b1.max():.2f}", "",
              "![usage](figures/encoder_kc_usage.png)", ""]

    # ---- 3. raster
    pick = np.concatenate([rng.choice(np.flatnonzero(b1 & (ds.gas == g)), 10, replace=False)
                           for g in sorted(GAS_NAMES)])
    R = H[pick]
    pref = np.vstack([R[ds.gas[pick] == g].mean(0) for g in sorted(GAS_NAMES)])
    col_order = np.lexsort((-pref.max(0), pref.argmax(0)))
    fig, axes = plt.subplots(2, 1, figsize=(12, 6))
    for ax, Rv, title in [(axes[0], R, "KCs in index order"),
                          (axes[1], R[:, col_order], "KCs sorted by the gas they fire for most (display only)")]:
        ax.imshow(Rv, aspect="auto", interpolation="nearest", cmap="Greys")
        ax.set_yticks(np.arange(5, 60, 10), [GAS_NAMES[g] for g in sorted(GAS_NAMES)])
        ax.set_title(title, fontsize=10)
    axes[1].set_xlabel("Kenyon cell")
    fig.suptitle(f"KC codes of 60 Batch-1 samples (10 per gas); each row has exactly {k} of {m} active")
    fig.tight_layout()
    fig.savefig(FIG / "encoder_raster.png", dpi=130)
    plt.close(fig)
    lines += ["## 4. Raster", "", "![raster](figures/encoder_raster.png)", ""]

    # ---- 4. overlap with Batch-1 codes over time
    gases = sorted(GAS_NAMES)
    ref = {g: rng.permutation(np.flatnonzero(b1 & (ds.gas == g)))[:MAX_PER_CELL] for g in gases}
    rows = []
    for g in gases:
        for b in range(1, N_BATCHES + 1):
            cell = np.flatnonzero((ds.batch == b) & (ds.gas == g))
            if len(cell) == 0:
                continue
            cell = rng.permutation(cell)[:MAX_PER_CELL]
            res = {"gas": g, "batch": b, "n": len(cell)}
            for space, F, sim in [("code", H, lambda a, c: jaccard_matrix(a, c, k)),
                                  ("input", P, cosine_matrix)]:
                same = sim(F[cell], F[ref[g]])
                if b == 1:  # exclude self-pairs
                    same = same[~np.equal.outer(cell, ref[g])]
                other = np.concatenate([sim(F[cell], F[ref[o]]).ravel() for o in gases if o != g])
                res[f"{space}_same"] = float(np.mean(same))
                res[f"{space}_other"] = float(np.mean(other))
            rows.append(res)
    fig, axes = plt.subplots(2, len(gases), figsize=(22, 6.5), sharey="row")
    for c, g in enumerate(gases):
        r = [x for x in rows if x["gas"] == g]
        bs = [x["batch"] for x in r]
        for row, space, ylab in [(0, "code", "Jaccard with Batch-1 codes"),
                                 (1, "input", "cosine with Batch-1 PN inputs")]:
            ax = axes[row, c]
            ax.plot(bs, [x[f"{space}_same"] for x in r], "o-", label="same gas in Batch 1")
            ax.plot(bs, [x[f"{space}_other"] for x in r], "s--", label="other gases in Batch 1")
            for x in r:
                if x["n"] < 20:
                    ax.axvspan(x["batch"] - .4, x["batch"] + .4, color="grey", alpha=.2, lw=0)
            ax.set_xticks(range(1, 11))
            if c == 0:
                ax.set_ylabel(ylab)
            if row == 0:
                ax.set_title(GAS_NAMES[g])
            if row == 1:
                ax.set_xlabel("batch")
    axes[0, -1].legend(fontsize=8)
    fig.suptitle("How similar is each batch's gas to Batch 1? Top: KC code overlap. "
                 "Bottom: input similarity. Grey = fewer than 20 samples.")
    fig.tight_layout()
    fig.savefig(FIG / "encoder_overlap_by_batch.png", dpi=130)
    plt.close(fig)

    tbl = ["| gas | batch | n | code same | code other | margin | input same | input other |",
           "|---|---|---|---|---|---|---|---|"]
    for x in rows:
        tbl.append(f"| {GAS_NAMES[x['gas']]} | {x['batch']} | {x['n']} | {x['code_same']:.3f} | "
                   f"{x['code_other']:.3f} | {x['code_same'] - x['code_other']:+.3f} | "
                   f"{x['input_same']:.3f} | {x['input_other']:.3f} |")
    lines += ["## 5. Overlap with Batch-1 codes over time", "",
              "For each gas and batch: mean similarity of that batch's samples to "
              "Batch-1 samples of the **same** gas vs. of **other** gases (up to "
              f"{MAX_PER_CELL} samples per cell). A negative code margin means the "
              "gas now looks more like other gases' Batch-1 codes than its own.", "",
              "![overlap](figures/encoder_overlap_by_batch.png)", "", *tbl, ""]
    (ROOT / "reports" / "phase3_encoder.md").write_text("\n".join(lines))
    print("\n".join(lines[:30]))


if __name__ == "__main__":
    main()
