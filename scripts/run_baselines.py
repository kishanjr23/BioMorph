"""Phase 2: run every conventional baseline under the chronological protocol.

Usage:
    python scripts/run_baselines.py               # 20 seeds, all methods, both preprocessings
    python scripts/run_baselines.py --seeds 2     # quick check

Writes
    results/baselines.csv         one row per method x prep x held-out gas x seed x batch
                                  (batch 1 = Batch-1 reference: CALIB vs held-out gas)
    results/baselines_tuning.csv  pseudo-novelty AUROC per config x pseudo-novel gas
    reports/figures/baselines_auroc_by_batch_{P1,P2}.png
    reports/figures/baselines_fpr_by_batch_{P1,P2}.png
    reports/phase2_baselines.md   summary tables generated from the CSV
"""

from __future__ import annotations

import argparse
import sys
import time
from datetime import date
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from joblib import Parallel, delayed

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from biomorph.baselines import METHODS  # noqa: E402
from biomorph.data import GAS_NAMES, load_all  # noqa: E402
from biomorph.experiment import run_split  # noqa: E402
from biomorph.preprocess import PREPROCESSINGS  # noqa: E402
from biomorph.protocol import HELDOUT_GASES, make_split  # noqa: E402

RESULTS = ROOT / "results"
FIG = ROOT / "reports" / "figures"


def one_job(ds, gas, seed, methods, preps):
    split = make_split(ds, gas, seed)
    rows, tuning = [], []
    for method in methods:
        for prep in preps:
            r, t, _ = run_split(ds, split, method, prep)
            rows += r
            tuning += t
    return rows, tuning


def plot_by_batch(df, metric, prep, path, ylabel, hline=None):
    d = df[df.prep == prep]
    fig, axes = plt.subplots(1, len(HELDOUT_GASES), figsize=(20, 4), sharey=True)
    for ax, gas in zip(axes, HELDOUT_GASES):
        g = d[d.heldout == gas]
        for method in METHODS:
            m = g[g.method == method]
            if m.empty:
                continue
            agg = m.groupby("batch")[metric]
            mean, lo, hi = agg.mean(), agg.quantile(0.025), agg.quantile(0.975)
            ls = "--" if METHODS[method].label_use == "class-aware" else "-"
            ax.plot(mean.index, mean.values, ls, marker="o", ms=3, label=method)
            ax.fill_between(mean.index, lo.values, hi.values, alpha=0.15)
        low = g[g.low_n].batch.unique()
        for b in low:
            ax.axvspan(b - 0.4, b + 0.4, color="grey", alpha=0.15, lw=0)
        if hline is not None:
            ax.axhline(hline, color="k", lw=0.8, ls=":")
        ax.set_title(f"held out: {GAS_NAMES[gas]}")
        ax.set_xlabel("batch (1 = Batch-1 reference)")
        ax.set_xticks(range(1, 11))
    axes[0].set_ylabel(ylabel)
    axes[-1].legend(fontsize=8, loc="best")
    fig.suptitle(f"{ylabel} by batch, {prep}. Line = mean over seeds, band = 2.5-97.5 "
                 f"percentile over seeds, grey = fewer than 20 unfamiliar samples, "
                 f"dashed = class-aware reference", fontsize=10)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def write_report(df, tuning, n_seeds, elapsed):
    test = df[df.batch >= 2]
    # per seed: mean over batches 2-10, then mean/sd over seeds
    per_seed = test.groupby(["prep", "method", "heldout_name", "seed"])[["auroc", "auprc", "fpr", "tpr"]].mean()

    def table(metric, prep):
        s = per_seed.loc[prep][metric].groupby(["method", "heldout_name"]).agg(["mean", "std"])
        cell = s.apply(lambda r: f"{r['mean']:.3f} ± {r['std']:.3f}", axis=1).unstack()
        cell = cell[[GAS_NAMES[g] for g in HELDOUT_GASES]]
        avg = per_seed.loc[prep][metric].groupby("method").mean()
        cell["mean over gases"] = avg.map(lambda v: f"{v:.3f}")
        cell = cell.reindex(list(METHODS))
        cell.insert(0, "labels", [METHODS[m].label_use for m in cell.index])
        return cell.to_markdown()

    ref = df[df.batch == 1].groupby(["prep", "method", "heldout_name"]).auroc.mean().unstack()
    ref = ref[[GAS_NAMES[g] for g in HELDOUT_GASES]]

    chosen = (tuning[tuning.chosen].drop_duplicates(["method", "prep", "heldout", "seed"])
              .groupby(["method", "prep"]).config.agg(lambda s: s.value_counts().head(3).to_dict()))

    lines = [
        "# Phase 2: conventional baseline results",
        "",
        f"Generated by `scripts/run_baselines.py` on {date.today()} "
        f"({n_seeds} seeds, {elapsed / 60:.1f} min). Every number below is computed "
        "from `results/baselines.csv`. No fly model exists yet.",
        "",
        "Protocol: train on Batch 1 without the held-out gas (70% FIT / 30% CALIB, "
        "seeded), tune by pseudo-novelty inside Batch 1, threshold = 95th percentile "
        "of CALIB scores, freeze, test on batches 2-10. Cells show mean ± SD over "
        "seeds of the per-seed average over batches 2-10. The SD reflects only "
        "FIT/CALIB split randomness (and Isolation Forest's own seed).",
        "",
        "Label-free methods are the main comparison for the fly model. Class-aware "
        "methods use gas labels and are a stronger reference only.",
        "",
    ]
    for prep in PREPROCESSINGS:
        lines += [f"## {prep}", "",
                  "### AUROC (0.5 = chance)", "", table("auroc", prep), "",
                  "### AUPRC (chance = unfamiliar share; see `data_audit.md` §3a)", "",
                  table("auprc", prep), "",
                  "### False-positive rate on familiar gases at the frozen threshold "
                  "(target in Batch 1: 0.05)", "", table("fpr", prep), "",
                  "### Unfamiliar-gas detection rate (TPR) at the frozen threshold", "",
                  table("tpr", prep), "",
                  f"![AUROC](figures/baselines_auroc_by_batch_{prep}.png)", "",
                  f"![FPR](figures/baselines_fpr_by_batch_{prep}.png)", ""]
    lines += ["## Batch-1 reference AUROC (CALIB familiar vs Batch-1 held-out gas, no drift)",
              "", ref.round(3).to_markdown(), "",
              "## Most frequently chosen configs (count over held-out gases x seeds)", "",
              chosen.to_frame().to_markdown(), ""]
    (ROOT / "reports" / "phase2_baselines.md").write_text("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--jobs", type=int, default=-1)
    ap.add_argument("--methods", nargs="+", default=list(METHODS))
    args = ap.parse_args()

    ds = load_all()
    t0 = time.time()
    out = Parallel(n_jobs=args.jobs, verbose=5)(
        delayed(one_job)(ds, g, s, args.methods, PREPROCESSINGS)
        for g in HELDOUT_GASES for s in range(args.seeds)
    )
    elapsed = time.time() - t0
    df = pd.DataFrame([r for rows, _ in out for r in rows])
    tuning = pd.DataFrame([t for _, ts in out for t in ts])

    RESULTS.mkdir(exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    df.to_csv(RESULTS / "baselines.csv", index=False)
    tuning.to_csv(RESULTS / "baselines_tuning.csv", index=False)
    for prep in PREPROCESSINGS:
        plot_by_batch(df, "auroc", prep, FIG / f"baselines_auroc_by_batch_{prep}.png", "AUROC", 0.5)
        plot_by_batch(df, "fpr", prep, FIG / f"baselines_fpr_by_batch_{prep}.png",
                      "FPR at frozen threshold", 0.05)
    write_report(df, tuning, args.seeds, elapsed)
    print(f"done in {elapsed / 60:.1f} min: {len(df)} metric rows")


if __name__ == "__main__":
    main()
