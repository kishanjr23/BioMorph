"""Phase 3 MVP slice: fly model (encoder + simple familiarity memory) on ONE
held-out gas (acetone), against kNN and Isolation Forest.

Usage:  python scripts/run_mvp.py

Only acetone is run on purpose: the full 5-gas fly run waits until the
pre-registration in Phase 5 is committed, so results for the other gases are
not seen before the analysis plan is fixed.

Same splits, seeds, tuning and threshold rule as the baselines (experiment.py),
so fly and baseline rows with the same (prep, seed) are paired.

Go/no-go bars (fixed BEFORE the first run, 2026-11-24):
    G1 leakage tests pass (tests/test_protocol.py, tests/test_fly.py)
    G2 every test batch contains familiar and unfamiliar samples
    G3 exactly k KCs active per sample, and < 50% of KCs dead in Batch 1
    G4 SD over 20 seeds of mean AUROC (batches 2-10) <= 0.05, for P1 and P2

Writes
    results/mvp_fly_acetone.csv
    reports/figures/mvp_acetone_auroc.png
    reports/figures/mvp_weights.png
    reports/phase3_mvp.md
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from joblib import Parallel, delayed

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from biomorph.data import load_all  # noqa: E402
from biomorph.experiment import run_split  # noqa: E402
from biomorph.fly import EPS_GRID  # noqa: E402
from biomorph.preprocess import PREPROCESSINGS  # noqa: E402
from biomorph.protocol import TEST_BATCHES, make_split  # noqa: E402

GAS = 5  # Acetone
N_SEEDS = 20
SD_BAR = 0.05
DEAD_BAR = 0.5
COMPARE = ["knn", "iforest"]


def job(ds, seed, prep):
    split = make_split(ds, GAS, seed)
    rows, tuning, model = run_split(ds, split, "fly", prep)
    H_fit = model.detector.encoder_.encode(model.prep.transform(ds.X[split.fit]))
    extra = {
        "dead_frac": float((H_fit.sum(0) == 0).mean()),
        "active_ok": bool((H_fit.sum(1) == model.detector.encoder_.k).all()),
        "w": model.detector.memory_.w_,
        "counts": model.detector.memory_.counts_,
        "eps": model.config["eps"],
    }
    return rows, tuning, extra, prep, seed


def main():
    ds = load_all()
    out = Parallel(n_jobs=-1)(delayed(job)(ds, s, p)
                              for p in PREPROCESSINGS for s in range(N_SEEDS))
    fly = pd.DataFrame([r for rows, *_ in out for r in rows])
    (ROOT / "results").mkdir(exist_ok=True)
    fly.to_csv(ROOT / "results" / "mvp_fly_acetone.csv", index=False)
    tuning = pd.DataFrame([t for _, ts, *_ in out for t in ts])
    extras = {(p, s): e for _, _, e, p, s in out}

    base = pd.read_csv(ROOT / "results" / "baselines.csv")
    base = base[(base.heldout == GAS) & (base.method.isin(COMPARE)) & (base.seed < N_SEEDS)]
    allm = pd.concat([fly, base], ignore_index=True)
    test = allm[allm.batch >= 2]
    per_seed = test.groupby(["prep", "method", "seed"])[["auroc", "auprc", "fpr", "tpr"]].mean()

    lines = ["# Phase 3 MVP: fly model vs kNN and Isolation Forest, acetone held out", "",
             f"Generated by `scripts/run_mvp.py` on {date.today()}. {N_SEEDS} seeds. "
             "Fly = ON/OFF PN input, m = 2000, s = 6, k = 100, memory w = eps^count, "
             f"eps tuned by pseudo-novelty over {EPS_GRID}. Same splits, tuning rule "
             "and threshold rule as the baselines. **One gas only; this is a "
             "pipeline check, not a project result.**", ""]

    # ---- summary table
    summ = per_seed.groupby(["prep", "method"]).agg(["mean", "std"])
    tbl = ["| prep | method | AUROC | AUPRC | FPR at θ | TPR at θ |", "|---|---|---|---|---|---|"]
    for (p, m), r in summ.iterrows():
        tbl.append(f"| {p} | {m} | " + " | ".join(
            f"{r[(c, 'mean')]:.3f} ± {r[(c, 'std')]:.3f}" for c in ["auroc", "auprc", "fpr", "tpr"]) + " |")
    lines += ["## Mean over batches 2-10 (mean ± SD over seeds)", "", *tbl, ""]

    # ---- paired differences
    lines += ["## Paired AUROC difference (fly minus baseline, same seed and split)", "",
              "| prep | baseline | mean diff | seeds favouring fly |", "|---|---|---|---|"]
    for p in PREPROCESSINGS:
        f = per_seed.loc[(p, "fly")].auroc
        for m in COMPARE:
            d = f - per_seed.loc[(p, m)].auroc
            lines.append(f"| {p} | {m} | {d.mean():+.3f} | {int((d > 0).sum())} / {len(d)} |")
    lines.append("")

    # ---- per batch
    pb = allm[allm.prep == "P1"].groupby(["method", "batch"]).auroc.mean().unstack().round(3)
    lines += ["## AUROC per batch, P1 (mean over seeds; batch 1 = Batch-1 reference)", "",
              pb.to_markdown(), ""]

    # ---- figure: AUROC by batch
    fig, axes = plt.subplots(1, 2, figsize=(12, 4), sharey=True)
    for ax, p in zip(axes, PREPROCESSINGS):
        d = allm[allm.prep == p]
        for m in ["fly"] + COMPARE:
            g = d[d.method == m].groupby("batch").auroc
            ax.plot(g.mean().index, g.mean().values, "o-", ms=3, label=m, lw=2 if m == "fly" else 1)
            ax.fill_between(g.mean().index, g.quantile(.025).values, g.quantile(.975).values, alpha=.15)
        ax.axhline(0.5, color="k", ls=":", lw=.8)
        ax.axvspan(3.6, 4.4, color="grey", alpha=.15, lw=0)
        ax.set_title(f"Acetone held out, {p}")
        ax.set_xlabel("batch (1 = Batch-1 reference)")
        ax.set_xticks(range(1, 11))
    axes[0].set_ylabel("AUROC")
    axes[0].legend()
    fig.suptitle("MVP: mean over 20 seeds, band = 2.5-97.5 percentile, grey = < 20 unfamiliar samples")
    fig.tight_layout()
    fig.savefig(ROOT / "reports" / "figures" / "mvp_acetone_auroc.png", dpi=130)
    plt.close(fig)

    # ---- memory saturation
    eps_counts = pd.Series([e["eps"] for e in extras.values()]).value_counts().to_dict()
    e0 = extras[("P1", 0)]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    axes[0].hist(e0["counts"], bins=50)
    axes[0].set_xlabel("c_i = number of FIT samples in which KC i fired")
    axes[0].set_ylabel("number of KCs")
    axes[1].hist(e0["w"], bins=50)
    axes[1].set_xlabel(f"w_i = eps^c_i after training (eps = {e0['eps']})")
    fig.suptitle("Memory after training, P1, seed 0, acetone held out")
    fig.tight_layout()
    fig.savefig(ROOT / "reports" / "figures" / "mvp_weights.png", dpi=130)
    plt.close(fig)
    w = e0["w"]
    lines += ["## Memory saturation (P1, seed 0)", "",
              f"- Chosen eps over all {len(extras)} runs: {eps_counts}",
              f"- Seed 0: eps = {e0['eps']}; KCs with w = 1 (never used): "
              f"{np.mean(w == 1):.1%}; w < 0.01 (saturated): {np.mean(w < 0.01):.1%}; "
              f"median count among used KCs: {np.median(e0['counts'][e0['counts'] > 0]):.0f}",
              "", "![weights](figures/mvp_weights.png)", ""]

    # ---- go/no-go
    sd = per_seed.xs("fly", level="method").auroc.groupby("prep").std()
    dead = max(e["dead_frac"] for e in extras.values())
    both = bool((fly[fly.batch >= 2].n_novel > 0).all() and (fly[fly.batch >= 2].n_fam > 0).all())
    g3 = all(e["active_ok"] for e in extras.values()) and dead < DEAD_BAR
    g4 = bool((sd <= SD_BAR).all())
    lines += ["## Go/no-go (bars fixed before the run)", "",
              "| check | result | pass |", "|---|---|---|",
              "| G1 leakage tests | run `pytest` (fly perturbation test included) | see test output |",
              f"| G2 both classes in every test batch | {both} | {'✅' if both else '❌'} |",
              f"| G3 exactly k active; dead KCs in FIT < {DEAD_BAR:.0%} | max dead = {dead:.1%} | {'✅' if g3 else '❌'} |",
              f"| G4 seed SD of mean AUROC ≤ {SD_BAR} | " +
              ", ".join(f"{p}: {v:.3f}" for p, v in sd.items()) + f" | {'✅' if g4 else '❌'} |", "",
              "![mvp](figures/mvp_acetone_auroc.png)", ""]
    (ROOT / "reports" / "phase3_mvp.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
